// 格式化 fixture 为给 LLM 的输入
export function formatFixture(fixture) {
  let text = `[决策] ${fixture.decision}\n\n[澄清问答]\n`;
  for (const { q, a } of fixture.clarifications) {
    text += `Q: ${q}\nA: ${a}\n\n`;
  }
  return text.trim();
}
